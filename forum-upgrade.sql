create or replace function public.list_my_forum_bookmarks()
returns table (post_id bigint, created_at timestamptz)
language plpgsql
stable
security definer
set search_path = public
as $$
begin
  if auth.uid() is null then raise exception 'AUTH_REQUIRED'; end if;
  return query
  select b.post_id, b.created_at
  from public.forum_bookmarks b
  where b.user_id = auth.uid()
  order by b.created_at desc;
end;
$$;

create or replace function public.toggle_forum_bookmark(p_post_id bigint)
returns boolean
language plpgsql
security definer
set search_path = public
as $$
declare
  already_bookmarked boolean;
begin
  if auth.uid() is null then raise exception 'AUTH_REQUIRED'; end if;
  if not exists(select 1 from public.forum_posts p where p.id = p_post_id) then raise exception 'TARGET_NOT_FOUND'; end if;
  select exists(
    select 1 from public.forum_bookmarks b
    where b.user_id = auth.uid() and b.post_id = p_post_id
  ) into already_bookmarked;
  if already_bookmarked then
    delete from public.forum_bookmarks b where b.user_id = auth.uid() and b.post_id = p_post_id;
    return false;
  end if;
  insert into public.forum_bookmarks(user_id, post_id) values (auth.uid(), p_post_id);
  return true;
end;
$$;

create or replace function public.record_forum_view(p_post_id bigint, p_viewer_key text default null)
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
  inserted_count integer := 0;
  total bigint;
  clean_key text := trim(coalesce(p_viewer_key, ''));
begin
  if not exists(select 1 from public.forum_posts p where p.id = p_post_id) then raise exception 'TARGET_NOT_FOUND'; end if;
  if auth.uid() is not null then
    insert into public.forum_post_views(post_id, viewer_id)
    values (p_post_id, auth.uid()) on conflict do nothing;
    get diagnostics inserted_count = row_count;
  elsif clean_key ~ '^[A-Za-z0-9_-]{16,80}$' then
    insert into public.forum_post_views(post_id, viewer_key)
    values (p_post_id, clean_key) on conflict do nothing;
    get diagnostics inserted_count = row_count;
  end if;
  if inserted_count > 0 then
    update public.forum_posts p set view_count = p.view_count + 1 where p.id = p_post_id;
  end if;
  select p.view_count into total from public.forum_posts p where p.id = p_post_id;
  return coalesce(total, 0);
end;
$$;

create or replace function public.get_forum_thread_state(p_post_id bigint)
returns table (bookmarked boolean, post_liked boolean, liked_reply_ids bigint[])
language sql
stable
security definer
set search_path = public
as $$
  select
    auth.uid() is not null and exists(
      select 1 from public.forum_bookmarks b
      where b.user_id = auth.uid() and b.post_id = p_post_id
    ),
    auth.uid() is not null and exists(
      select 1 from public.forum_reactions r
      where r.user_id = auth.uid() and r.target_type = 'post' and r.target_id = p_post_id
    ),
    coalesce(array(
      select r.target_id from public.forum_reactions r
      join public.forum_replies reply on reply.id = r.target_id
      where r.user_id = auth.uid() and r.target_type = 'reply' and reply.post_id = p_post_id
    ), '{}'::bigint[]);
$$;

create or replace function public.admin_set_forum_post_status(
  p_post_id bigint,
  p_is_pinned boolean,
  p_is_featured boolean
)
returns boolean
language plpgsql
security definer
set search_path = public
as $$
declare
  post_author uuid;
  post_title text;
begin
  if not public.current_user_is_admin() then raise exception 'ADMIN_REQUIRED'; end if;
  select p.author_id, p.title into post_author, post_title
  from public.forum_posts p where p.id = p_post_id for update;
  if not found then raise exception 'TARGET_NOT_FOUND'; end if;
  update public.forum_posts p
  set is_pinned = coalesce(p_is_pinned, false), is_featured = coalesce(p_is_featured, false)
  where p.id = p_post_id;
  insert into public.moderation_actions(actor_id, action, target_user_id, details)
  values (auth.uid(), 'manage_forum_post', post_author,
    jsonb_build_object('post_id', p_post_id, 'title', post_title,
      'is_pinned', coalesce(p_is_pinned, false), 'is_featured', coalesce(p_is_featured, false)));
  return true;
end;
$$;

