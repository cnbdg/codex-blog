create or replace function public.notify_forum_reply_created()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  recipient uuid;
  post_title text;
  notice_message text;
begin
  select p.title into post_title from public.forum_posts p where p.id = new.post_id;
  if new.parent_id is not null then
    select r.author_id into recipient from public.forum_replies r where r.id = new.parent_id;
    notice_message := '回复了你的楼层';
  else
    select p.author_id into recipient from public.forum_posts p where p.id = new.post_id;
    notice_message := '回复了你的帖子';
  end if;
  if recipient is not null and recipient <> new.author_id then
    insert into public.notifications(recipient_id, actor_id, kind, target_type, target_id, payload)
    values (recipient, new.author_id, 'forum_reply', 'forum_post', new.post_id,
      jsonb_build_object('message', notice_message, 'title', post_title,
        'floor', new.floor_number, 'reply_id', new.id));
  end if;
  return new;
end;
$$;

