-- 参考贴吧的帖子信息流、精品/置顶、收藏、楼层浏览与回复通知；不创建分区或“吧”。
-- 前置：community.sql、forum-interactions.sql、social-inbox.sql、governance.sql。
-- 可重复执行，不会删除帖子、回复、用户、点赞或既有通知。

alter table public.forum_posts
  add column if not exists topic_type text not null default 'discussion',
  add column if not exists is_pinned boolean not null default false,
  add column if not exists is_featured boolean not null default false,
  add column if not exists view_count bigint not null default 0;

do $$
begin
  if not exists (
    select 1 from pg_constraint
    where conname = 'forum_posts_topic_type_check'
      and conrelid = 'public.forum_posts'::regclass
  ) then
    alter table public.forum_posts add constraint forum_posts_topic_type_check
      check (topic_type in ('discussion', 'question', 'share', 'guide'));
  end if;
  if not exists (
    select 1 from pg_constraint
    where conname = 'forum_posts_view_count_check'
      and conrelid = 'public.forum_posts'::regclass
  ) then
    alter table public.forum_posts add constraint forum_posts_view_count_check
      check (view_count >= 0);
  end if;
end
$$;

create index if not exists forum_posts_pinned_updated_idx
  on public.forum_posts(is_pinned desc, updated_at desc);
create index if not exists forum_posts_featured_updated_idx
  on public.forum_posts(is_featured, updated_at desc)
  where is_featured = true;
create index if not exists forum_posts_topic_type_updated_idx
  on public.forum_posts(topic_type, updated_at desc);

-- 普通用户只能新增/修改帖子正文、标题和类型，不能直接给自己置顶、加精或刷浏览量。
