create or replace function public.normalize_forum_post_write()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if tg_op = 'INSERT' then
    new.created_at := now();
    new.updated_at := now();
    new.is_pinned := false;
    new.is_featured := false;
    new.view_count := 0;
    new.likes := 0;
  -- community.sql 的回复触发器会嵌套更新帖子时间；仅允许这类数据库内部更新通过。
  elsif pg_trigger_depth() > 1 and new.updated_at is distinct from old.updated_at then
    new.updated_at := new.updated_at;
  elsif new.title is distinct from old.title
     or new.content is distinct from old.content
     or new.topic_type is distinct from old.topic_type then
    new.updated_at := now();
  else
    new.updated_at := old.updated_at;
  end if;
  return new;
end;
$$;

drop trigger if exists normalize_forum_post_write_trigger on public.forum_posts;
create trigger normalize_forum_post_write_trigger
  before insert or update on public.forum_posts
  for each row execute function public.normalize_forum_post_write();

create table if not exists public.forum_bookmarks (
  user_id uuid not null references public.profiles(id) on delete cascade,
  post_id bigint not null references public.forum_posts(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (user_id, post_id)
);

create index if not exists forum_bookmarks_user_created_idx
  on public.forum_bookmarks(user_id, created_at desc);

create table if not exists public.forum_post_views (
  id bigint generated by default as identity primary key,
  post_id bigint not null references public.forum_posts(id) on delete cascade,
  viewer_id uuid references public.profiles(id) on delete cascade,
  viewer_key text,
  viewed_on date not null default current_date,
  created_at timestamptz not null default now(),
  check (
    (viewer_id is not null and viewer_key is null)
    or (viewer_id is null and viewer_key is not null and char_length(viewer_key) between 16 and 80)
  )
);

create unique index if not exists forum_post_views_user_day_idx
  on public.forum_post_views(post_id, viewer_id, viewed_on)
  where viewer_id is not null;
create unique index if not exists forum_post_views_guest_day_idx
  on public.forum_post_views(post_id, viewer_key, viewed_on)
  where viewer_id is null;

alter table public.forum_bookmarks enable row level security;
alter table public.forum_post_views enable row level security;
revoke all on table public.forum_bookmarks from anon, authenticated;
revoke all on table public.forum_post_views from anon, authenticated;

