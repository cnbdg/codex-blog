create index if not exists group_chat_members_user_idx
  on public.group_chat_members(user_id, joined_at desc);
create index if not exists group_chat_messages_group_created_idx
  on public.group_chat_messages(group_id, created_at desc);

alter table public.group_chats enable row level security;
alter table public.group_chat_members enable row level security;
alter table public.group_chat_messages enable row level security;
revoke all on public.group_chats, public.group_chat_members, public.group_chat_messages from anon, authenticated;

create or replace function public.is_group_chat_member(requested_group uuid, requested_user uuid default auth.uid())
returns boolean
language sql stable security definer set search_path = public
as $$
  select requested_user is not null and exists (
    select 1 from public.group_chat_members
    where group_id = requested_group and user_id = requested_user
  );
$$;

create or replace function public.can_manage_group_chat(requested_group uuid, requested_user uuid default auth.uid())
returns boolean
language sql stable security definer set search_path = public
as $$
  select requested_user is not null and exists (
    select 1 from public.group_chat_members
    where group_id = requested_group
      and user_id = requested_user
      and role in ('owner', 'admin')
  );
$$;

drop policy if exists "Group members can receive group messages" on public.group_chat_messages;
create policy "Group members can receive group messages"
  on public.group_chat_messages for select to authenticated
  using (public.is_group_chat_member(group_id, (select auth.uid())));
grant select on public.group_chat_messages to authenticated;

create or replace function public.create_group_chat(
  p_name text,
  p_description text default '',
  p_avatar_url text default null,
  p_member_ids uuid[] default '{}'::uuid[]
)
returns uuid
language plpgsql security definer set search_path = public
as $$
declare
  new_group_id uuid;
  clean_name text := trim(coalesce(p_name, ''));
  clean_description text := trim(coalesce(p_description, ''));
  clean_avatar text := nullif(trim(coalesce(p_avatar_url, '')), '');
  clean_members uuid[];
  valid_members integer;
begin
  if auth.uid() is null then raise exception 'AUTH_REQUIRED'; end if;
  if char_length(clean_name) not between 2 and 40 then raise exception 'INVALID_GROUP_NAME'; end if;
  if char_length(clean_description) > 200 then raise exception 'INVALID_GROUP_DESCRIPTION'; end if;
  if clean_avatar is not null and char_length(clean_avatar) > 500 then raise exception 'INVALID_GROUP_AVATAR'; end if;

  select coalesce(array_agg(distinct member_id), '{}'::uuid[])
    into clean_members
  from unnest(coalesce(p_member_ids, '{}'::uuid[])) as member_id
  where member_id is not null and member_id <> auth.uid();

  if cardinality(clean_members) < 1 then raise exception 'GROUP_MEMBER_REQUIRED'; end if;
  if cardinality(clean_members) > 49 then raise exception 'GROUP_MEMBER_LIMIT'; end if;

  select count(*) into valid_members
  from unnest(clean_members) as member_id
  where exists (
      select 1 from public.user_follows
      where follower_id = auth.uid() and following_id = member_id
    ) and exists (
      select 1 from public.user_follows
      where follower_id = member_id and following_id = auth.uid()
    );
  if valid_members <> cardinality(clean_members) then raise exception 'MUTUAL_FOLLOW_REQUIRED'; end if;

  insert into public.group_chats(owner_id, name, description, avatar_url)
  values (auth.uid(), clean_name, clean_description, clean_avatar)
  returning id into new_group_id;

  insert into public.group_chat_members(group_id, user_id, role)
  values (new_group_id, auth.uid(), 'owner');
  insert into public.group_chat_members(group_id, user_id, role)
  select new_group_id, member_id, 'member' from unnest(clean_members) as member_id;
  insert into public.notifications(recipient_id, actor_id, kind, target_type, payload)
  select member_id, auth.uid(), 'group_message', 'group_chat', jsonb_build_object(
    'event', 'group_invite',
    'message', '邀请你加入群聊',
    'preview', '邀请你加入群聊',
    'group_id', new_group_id,
    'group_name', clean_name,
    'sender_name', coalesce((select username from public.profiles where id = auth.uid()), '社区用户'),
    'sender_avatar_url', (select avatar_url from public.profiles where id = auth.uid())
  ) from unnest(clean_members) as member_id;
  return new_group_id;
end;
$$;

create or replace function public.list_my_group_chats()
returns table (
  group_id uuid,
  group_name text,
  group_description text,
  group_avatar_url text,
  owner_id uuid,
  group_role text,
  member_count bigint,
  unread_count bigint,
  last_message text,
  last_message_at timestamptz,
  last_sender_name text
)
language sql stable security definer set search_path = public
as $$
  select g.id, g.name, g.description, g.avatar_url, g.owner_id, mine.role,
    (select count(*) from public.group_chat_members members where members.group_id = g.id),
    (select count(*) from public.group_chat_messages unread
      where unread.group_id = g.id
        and unread.sender_id <> auth.uid()
        and unread.created_at > mine.last_read_at),
    latest.content, latest.created_at, latest.sender_name
  from public.group_chat_members mine
  join public.group_chats g on g.id = mine.group_id
  left join lateral (
    select message.content, message.created_at, coalesce(sender.username, '社区用户') as sender_name
    from public.group_chat_messages message
    left join public.profiles sender on sender.id = message.sender_id
    where message.group_id = g.id
    order by message.created_at desc
    limit 1
  ) latest on true
  where mine.user_id = auth.uid()
  order by coalesce(latest.created_at, g.created_at) desc;
$$;

drop function if exists public.list_group_chat_messages(uuid, integer);
create function public.list_group_chat_messages(p_group_id uuid, p_limit integer default 120)
returns table (
  id bigint,
  group_id uuid,
  sender_id uuid,
  content text,
  media_path text,
  created_at timestamptz,
  sender_username text,
  sender_avatar_url text,
  sender_uid bigint,
  sender_title text,
  revoked_at timestamptz,
  reply_to_id bigint,
  reply_sender_id uuid,
  reply_sender_name text,
  reply_content text,
  reply_media_path text,
  reply_created_at timestamptz,
  reply_revoked_at timestamptz
)
language plpgsql stable security definer set search_path = public as $$
begin
  if auth.uid() is null then raise exception 'AUTH_REQUIRED'; end if;
  if not public.is_group_chat_member(p_group_id, auth.uid()) then raise exception 'GROUP_MEMBERSHIP_REQUIRED'; end if;
  return query
  select ordered.id, ordered.group_id, ordered.sender_id, ordered.content, ordered.media_path, ordered.created_at,
    ordered.sender_username, ordered.sender_avatar_url, ordered.sender_uid, ordered.sender_title, ordered.revoked_at,
    quoted.id as reply_to_id, quoted.sender_id as reply_sender_id,
    coalesce(quoted_sender.username, '社区用户') as reply_sender_name,
    quoted.content as reply_content, quoted.media_path as reply_media_path, quoted.created_at as reply_created_at,
    quoted.revoked_at as reply_revoked_at
  from (
    select message.id, message.group_id, message.sender_id, message.content, message.media_path, message.created_at, message.reply_to_id, message.revoked_at,
      coalesce(sender.username, '社区用户') as sender_username, sender.avatar_url as sender_avatar_url,
      sender.user_uid as sender_uid, sender.display_title as sender_title
    from public.group_chat_messages message
    left join public.profiles sender on sender.id = message.sender_id
    where message.group_id = p_group_id
    order by message.created_at desc
    limit least(greatest(coalesce(p_limit, 120), 1), 200)
  ) ordered
  left join public.group_chat_messages quoted on quoted.id = ordered.reply_to_id
  left join public.profiles quoted_sender on quoted_sender.id = quoted.sender_id
  order by ordered.created_at asc;
end;
$$;

create or replace function public.send_group_chat_message(p_group_id uuid, p_content text)
returns bigint
language plpgsql security definer set search_path = public
as $$
declare
  new_message_id bigint;
  clean_content text := trim(coalesce(p_content, ''));
begin
  if auth.uid() is null then raise exception 'AUTH_REQUIRED'; end if;
  if not public.is_group_chat_member(p_group_id, auth.uid()) then raise exception 'GROUP_MEMBERSHIP_REQUIRED'; end if;
  if char_length(clean_content) not between 1 and 2000 then raise exception 'INVALID_MESSAGE'; end if;
  insert into public.group_chat_messages(group_id, sender_id, content)
  values (p_group_id, auth.uid(), clean_content)
  returning id into new_message_id;
  update public.group_chat_members set last_read_at = now()
  where group_id = p_group_id and user_id = auth.uid();
  return new_message_id;
end;
$$;

create or replace function public.mark_group_chat_read(p_group_id uuid)
returns void
language plpgsql security definer set search_path = public
as $$
begin
  if auth.uid() is null then raise exception 'AUTH_REQUIRED'; end if;
  if not public.is_group_chat_member(p_group_id, auth.uid()) then raise exception 'GROUP_MEMBERSHIP_REQUIRED'; end if;
  update public.group_chat_members set last_read_at = now()
  where group_id = p_group_id and user_id = auth.uid();
  update public.notifications set read_at = now()
  where recipient_id = auth.uid()
    and kind = 'group_message'
    and read_at is null
    and payload->>'group_id' = p_group_id::text;
end;
$$;

create or replace function public.list_group_chat_members(p_group_id uuid)
returns table (
  user_id uuid,
  user_uid bigint,
  username text,
  avatar_url text,
  display_title text,
  member_role text,
  joined_at timestamptz
)
language plpgsql stable security definer set search_path = public
as $$
begin
  if auth.uid() is null then raise exception 'AUTH_REQUIRED'; end if;
  if not public.is_group_chat_member(p_group_id, auth.uid()) then raise exception 'GROUP_MEMBERSHIP_REQUIRED'; end if;
  return query
    select member.user_id, profile.user_uid, profile.username, profile.avatar_url,
      profile.display_title, member.role, member.joined_at
    from public.group_chat_members member
    join public.profiles profile on profile.id = member.user_id
    where member.group_id = p_group_id
    order by case member.role when 'owner' then 0 when 'admin' then 1 else 2 end,
      member.joined_at asc;
end;
$$;

create or replace function public.update_group_chat(
  p_group_id uuid,
  p_name text,
  p_description text default '',
  p_avatar_url text default null
)
returns boolean
language plpgsql security definer set search_path = public
as $$
declare
  clean_name text := trim(coalesce(p_name, ''));
  clean_description text := trim(coalesce(p_description, ''));
  clean_avatar text := nullif(trim(coalesce(p_avatar_url, '')), '');
begin
  if not public.can_manage_group_chat(p_group_id, auth.uid()) then raise exception 'GROUP_ADMIN_REQUIRED'; end if;
  if char_length(clean_name) not between 2 and 40 then raise exception 'INVALID_GROUP_NAME'; end if;
  if char_length(clean_description) > 200 then raise exception 'INVALID_GROUP_DESCRIPTION'; end if;
  if clean_avatar is not null and char_length(clean_avatar) > 500 then raise exception 'INVALID_GROUP_AVATAR'; end if;
  update public.group_chats set name = clean_name, description = clean_description,
    avatar_url = clean_avatar, updated_at = now()
  where id = p_group_id;
  return found;
end;
$$;

create or replace function public.add_group_chat_members(p_group_id uuid, p_member_ids uuid[])
returns integer
language plpgsql security definer set search_path = public
as $$
declare
  clean_members uuid[];
  valid_members integer;
  current_count integer;
  inserted_count integer;
begin
  if not public.can_manage_group_chat(p_group_id, auth.uid()) then raise exception 'GROUP_ADMIN_REQUIRED'; end if;
  select coalesce(array_agg(distinct member_id), '{}'::uuid[]) into clean_members
  from unnest(coalesce(p_member_ids, '{}'::uuid[])) as member_id
  where member_id is not null
    and member_id <> auth.uid()
    and not exists (
      select 1 from public.group_chat_members existing
      where existing.group_id = p_group_id and existing.user_id = member_id
    );
  if cardinality(clean_members) < 1 then return 0; end if;
  select count(*) into current_count from public.group_chat_members where group_id = p_group_id;
  if current_count + cardinality(clean_members) > 50 then raise exception 'GROUP_MEMBER_LIMIT'; end if;
  select count(*) into valid_members from unnest(clean_members) as member_id
  where exists (select 1 from public.user_follows where follower_id = auth.uid() and following_id = member_id)
    and exists (select 1 from public.user_follows where follower_id = member_id and following_id = auth.uid());
  if valid_members <> cardinality(clean_members) then raise exception 'MUTUAL_FOLLOW_REQUIRED'; end if;
  insert into public.group_chat_members(group_id, user_id, role)
  select p_group_id, member_id, 'member' from unnest(clean_members) as member_id
  on conflict (group_id, user_id) do nothing;
  get diagnostics inserted_count = row_count;
  insert into public.notifications(recipient_id, actor_id, kind, target_type, payload)
  select member_id, auth.uid(), 'group_message', 'group_chat', jsonb_build_object(
    'event', 'group_invite',
    'message', '邀请你加入群聊',
    'preview', '邀请你加入群聊',
    'group_id', p_group_id,
    'group_name', coalesce((select name from public.group_chats where id = p_group_id), '群聊'),
    'sender_name', coalesce((select username from public.profiles where id = auth.uid()), '社区用户'),
    'sender_avatar_url', (select avatar_url from public.profiles where id = auth.uid())
  ) from unnest(clean_members) as member_id;
  return inserted_count;
end;
$$;

create or replace function public.remove_group_chat_member(p_group_id uuid, p_user_id uuid)
returns boolean
language plpgsql security definer set search_path = public
as $$
declare
  caller_role text;
  target_role text;
begin
  select role into caller_role from public.group_chat_members
  where group_id = p_group_id and user_id = auth.uid();
  select role into target_role from public.group_chat_members
  where group_id = p_group_id and user_id = p_user_id;
  if caller_role is null or caller_role not in ('owner', 'admin') then raise exception 'GROUP_ADMIN_REQUIRED'; end if;
  if target_role is null then return false; end if;
  if target_role = 'owner' or (target_role = 'admin' and caller_role <> 'owner') then raise exception 'CANNOT_REMOVE_GROUP_ADMIN'; end if;
  if p_user_id = auth.uid() then raise exception 'USE_LEAVE_GROUP'; end if;
  delete from public.notifications
  where recipient_id = p_user_id
    and kind = 'group_message'
    and payload->>'group_id' = p_group_id::text;
  delete from public.group_chat_members where group_id = p_group_id and user_id = p_user_id;
  return found;
end;
$$;

create or replace function public.leave_group_chat(p_group_id uuid)
returns boolean
language plpgsql security definer set search_path = public
as $$
declare
  leaving_role text;
  successor uuid;
begin
  if auth.uid() is null then raise exception 'AUTH_REQUIRED'; end if;
  select role into leaving_role from public.group_chat_members
  where group_id = p_group_id and user_id = auth.uid();
  if leaving_role is null then return false; end if;
  if leaving_role = 'owner' then
    select user_id into successor from public.group_chat_members
    where group_id = p_group_id and user_id <> auth.uid()
    order by case role when 'admin' then 0 else 1 end, joined_at asc limit 1;
    if successor is null then
      delete from public.notifications
      where kind = 'group_message' and payload->>'group_id' = p_group_id::text;
      delete from public.group_chats where id = p_group_id;
      return true;
    end if;
    update public.group_chat_members set role = 'owner'
    where group_id = p_group_id and user_id = successor;
    update public.group_chats set owner_id = successor, updated_at = now()
    where id = p_group_id;
  end if;
  delete from public.notifications
  where recipient_id = auth.uid()
    and kind = 'group_message'
    and payload->>'group_id' = p_group_id::text;
  delete from public.group_chat_members where group_id = p_group_id and user_id = auth.uid();
  return found;
end;
$$;

