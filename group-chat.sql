create or replace function public.notify_group_chat_message_created()
returns trigger language plpgsql security definer set search_path = public
as $$
declare
  sender_name text;
  sender_avatar text;
  current_group_name text;
begin
  select username, avatar_url into sender_name, sender_avatar
  from public.profiles where id = new.sender_id;
  select name into current_group_name from public.group_chats where id = new.group_id;
  insert into public.notifications(recipient_id, actor_id, kind, target_type, payload)
  select member.user_id, new.sender_id, 'group_message', 'group_chat',
    jsonb_build_object(
      'message', '在群聊中发送了新消息',
      'preview', left(regexp_replace(new.content, '[[:space:]]+', ' ', 'g'), 80),
      'group_id', new.group_id,
      'group_name', coalesce(current_group_name, '群聊'),
      'sender_name', coalesce(sender_name, '社区用户'),
      'sender_avatar_url', sender_avatar
    )
  from public.group_chat_members member
  where member.group_id = new.group_id and member.user_id <> new.sender_id;
  return new;
end;
$$;

drop trigger if exists after_group_chat_message_created on public.group_chat_messages;
create trigger after_group_chat_message_created
  after insert on public.group_chat_messages
  for each row execute procedure public.notify_group_chat_message_created();

