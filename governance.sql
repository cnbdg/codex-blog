create or replace function public.admin_list_moderation_reports(
  status_filter text default 'all',
  search_text text default '',
  row_limit integer default 100
)
returns table (
  report_id bigint,
  target_type text,
  target_id bigint,
  category text,
  priority text,
  reason text,
  status text,
  created_at timestamptz,
  reporter_name text,
  target_author_id uuid,
  target_author_uid bigint,
  target_author_name text,
  target_author_title text,
  content_excerpt text,
  decision text,
  review_note text,
  reviewed_at timestamptz,
  reviewer_name text
)
language plpgsql
stable
security definer
set search_path = public
as $$
begin
  if not public.current_user_is_admin() then raise exception 'ADMIN_REQUIRED'; end if;
  return query
  with report_rows as (
    select r.*,
      case r.target_type
        when 'forum_post' then (select fp.author_id from public.forum_posts fp where fp.id = r.target_id)
        when 'forum_reply' then (select fr.author_id from public.forum_replies fr where fr.id = r.target_id)
        else (select c.author_id from public.comments c where c.id = r.target_id)
      end as author_id,
      left(coalesce(case r.target_type
        when 'forum_post' then (select fp.title || E'\n' || fp.content from public.forum_posts fp where fp.id = r.target_id)
        when 'forum_reply' then (select fr.content from public.forum_replies fr where fr.id = r.target_id)
        else (select c.content from public.comments c where c.id = r.target_id)
      end, '[内容已删除]'), 500) as excerpt
    from public.content_reports r
  )
  select q.id, q.target_type, q.target_id, q.category, q.priority, q.reason, q.status, q.created_at,
    reporter.username, author.id, author.user_uid, author.username, author.display_title, q.excerpt,
    q.decision, q.review_note, q.reviewed_at, reviewer.username
  from report_rows q
  join public.profiles reporter on reporter.id = q.reporter_id
  left join public.profiles author on author.id = q.author_id
  left join public.profiles reviewer on reviewer.id = q.reviewed_by
  where (status_filter = 'all' or q.status = status_filter)
    and (
      trim(coalesce(search_text, '')) = ''
      or q.reason ilike '%' || trim(search_text) || '%'
      or q.excerpt ilike '%' || trim(search_text) || '%'
      or reporter.username ilike '%' || trim(search_text) || '%'
      or author.username ilike '%' || trim(search_text) || '%'
      or author.user_uid::text = trim(search_text)
    )
  order by (q.status = 'pending') desc, (q.priority = 'urgent') desc, (q.priority = 'high') desc, q.created_at desc
  limit greatest(1, least(coalesce(row_limit, 100), 300));
end;
$$;

