create or replace function public.admin_resolve_report(
  target_report_id bigint,
  review_decision text,
  violation_category text,
  penalty_code text,
  moderator_note text
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  item public.content_reports%rowtype;
  author_id uuid;
  content_snapshot text;
  effective_penalty text := coalesce(penalty_code, 'none');
  restricted_until timestamptz;
  strike_number bigint := 0;
  strike_points smallint := 1;
begin
  if not public.current_user_is_admin() then raise exception 'ADMIN_REQUIRED'; end if;
  if review_decision not in ('dismiss', 'warn', 'delete', 'delete_penalty') then raise exception 'INVALID_DECISION'; end if;
  if violation_category not in ('harassment', 'privacy', 'spam', 'illegal', 'misinformation', 'other') then raise exception 'INVALID_CATEGORY'; end if;
  if effective_penalty not in ('none', 'auto', '3d', '7d', '30d', 'permanent') then raise exception 'INVALID_PENALTY'; end if;
  if char_length(trim(moderator_note)) not between 2 and 500 then raise exception 'REVIEW_NOTE_REQUIRED'; end if;

  select * into item from public.content_reports where id = target_report_id for update;
  if not found then raise exception 'REPORT_NOT_FOUND'; end if;
  if item.status <> 'pending' then raise exception 'CASE_ALREADY_REVIEWED'; end if;

  if item.target_type = 'forum_post' then
    select fp.author_id, left(fp.title || E'\n' || fp.content, 500) into author_id, content_snapshot
    from public.forum_posts fp where fp.id = item.target_id;
  elsif item.target_type = 'forum_reply' then
    select fr.author_id, left(fr.content, 500) into author_id, content_snapshot
    from public.forum_replies fr where fr.id = item.target_id;
  else
    select c.author_id, left(c.content, 500) into author_id, content_snapshot
    from public.comments c where c.id = item.target_id;
  end if;

  if review_decision in ('delete', 'delete_penalty') then
    if item.target_type = 'forum_post' then delete from public.forum_posts where id = item.target_id;
    elsif item.target_type = 'forum_reply' then delete from public.forum_replies where id = item.target_id;
    else delete from public.comments where id = item.target_id;
    end if;
  end if;

  if review_decision <> 'dismiss' and author_id is not null
     and not exists(select 1 from public.profiles p where p.id = author_id and p.is_admin = true) then
    strike_points := case when review_decision = 'warn' then 1 when review_decision = 'delete' then 2 else 3 end;
    insert into public.moderation_strikes(user_id, report_id, category, points, reason, created_by)
    values (author_id, item.id, violation_category, strike_points, trim(moderator_note), auth.uid());
    select count(*) into strike_number from public.moderation_strikes s where s.user_id = author_id;
  end if;

  if review_decision <> 'delete_penalty' then effective_penalty := 'none'; end if;
  if effective_penalty = 'auto' then
    effective_penalty := case when strike_number <= 1 then '3d' when strike_number = 2 then '7d' else 'permanent' end;
  end if;
  restricted_until := case effective_penalty
    when '3d' then now() + interval '3 days'
    when '7d' then now() + interval '7 days'
    when '30d' then now() + interval '30 days'
    else null
  end;

  if effective_penalty <> 'none' and author_id is not null then
    if author_id = auth.uid() then raise exception 'CANNOT_BAN_SELF'; end if;
    if exists(select 1 from public.profiles p where p.id = author_id and p.is_admin = true) then raise exception 'CANNOT_BAN_ADMIN'; end if;
    insert into public.user_moderation(user_id, banned_until, reason, updated_at, updated_by, active, category, scope)
    values (author_id, restricted_until, trim(moderator_note), now(), auth.uid(), true, violation_category, 'community')
    on conflict (user_id) do update set
      banned_until = excluded.banned_until, reason = excluded.reason, updated_at = now(), updated_by = auth.uid(),
      active = true, category = excluded.category, scope = excluded.scope;
  end if;

  if review_decision in ('delete', 'delete_penalty') then
    update public.content_reports r set
      status = 'resolved', reviewed_at = now(), reviewed_by = auth.uid(), category = violation_category,
      decision = review_decision, review_note = trim(moderator_note)
    where r.target_type = item.target_type and r.target_id = item.target_id and r.status = 'pending';
  else
    update public.content_reports r set
      status = case when review_decision = 'dismiss' then 'dismissed' else 'resolved' end,
      reviewed_at = now(), reviewed_by = auth.uid(), category = violation_category,
      decision = review_decision, review_note = trim(moderator_note)
    where r.id = item.id;
  end if;

  insert into public.moderation_actions(actor_id, action, target_user_id, report_id, details)
  values (auth.uid(), 'resolve_report', author_id, item.id, jsonb_build_object(
    'decision', review_decision, 'category', violation_category, 'penalty', effective_penalty,
    'restricted_until', restricted_until, 'note', trim(moderator_note),
    'target_type', item.target_type, 'target_id', item.target_id,
    'content_snapshot', coalesce(content_snapshot, '[内容已删除]'), 'strike_number', strike_number
  ));

  return jsonb_build_object('decision', review_decision, 'penalty', effective_penalty,
    'restricted_until', restricted_until, 'target_user_id', author_id);
end;
$$;

create or replace function public.admin_manage_member(
  target_user uuid,
  new_title text,
  role_action text default 'keep'
)
returns boolean
language plpgsql
security definer
set search_path = public
as $$
declare
  target_is_admin boolean;
  admin_count bigint;
begin
  if not public.current_user_is_admin() then raise exception 'ADMIN_REQUIRED'; end if;
  if role_action not in ('keep', 'promote', 'demote') then raise exception 'INVALID_ROLE_ACTION'; end if;
  if char_length(trim(new_title)) not between 1 and 30 then raise exception 'INVALID_TITLE'; end if;
  select p.is_admin into target_is_admin from public.profiles p where p.id = target_user for update;
  if not found then raise exception 'USER_NOT_FOUND'; end if;

  if role_action <> 'keep' and target_user = auth.uid() then raise exception 'CANNOT_CHANGE_SELF_ROLE'; end if;
  if role_action = 'demote' and target_is_admin then
    select count(*) into admin_count from public.profiles p where p.is_admin = true;
    if admin_count <= 1 then raise exception 'CANNOT_DEMOTE_LAST_ADMIN'; end if;
  end if;

  update public.profiles p set
    display_title = trim(new_title),
    title_locked = true,
    is_admin = case role_action when 'promote' then true when 'demote' then false else p.is_admin end
  where p.id = target_user;

  insert into public.moderation_actions(actor_id, action, target_user_id, details)
  values (auth.uid(), 'manage_member', target_user,
    jsonb_build_object('title', trim(new_title), 'role_action', role_action, 'previous_admin', target_is_admin));
  return true;
end;
$$;

