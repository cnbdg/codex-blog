create or replace function public.admin_set_user_restriction(
  target_user uuid,
  duration_code text,
  violation_category text,
  restriction_reason text
)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  until_value timestamptz;
begin
  if not public.current_user_is_admin() then raise exception 'ADMIN_REQUIRED'; end if;
  if target_user = auth.uid() then raise exception 'CANNOT_BAN_SELF'; end if;
  if not exists(select 1 from public.profiles p where p.id = target_user) then raise exception 'USER_NOT_FOUND'; end if;
  if exists(select 1 from public.profiles p where p.id = target_user and p.is_admin = true) then raise exception 'CANNOT_BAN_ADMIN'; end if;
  if violation_category not in ('harassment', 'privacy', 'spam', 'illegal', 'misinformation', 'other') then raise exception 'INVALID_CATEGORY'; end if;
  if duration_code not in ('3d', '7d', '30d', 'permanent') then raise exception 'INVALID_DURATION'; end if;
  if char_length(trim(restriction_reason)) not between 2 and 300 then raise exception 'INVALID_REASON'; end if;

  until_value := case duration_code
    when '3d' then now() + interval '3 days'
    when '7d' then now() + interval '7 days'
    when '30d' then now() + interval '30 days'
    else null
  end;

  insert into public.user_moderation(user_id, banned_until, reason, updated_at, updated_by, active, category, scope)
  values (target_user, until_value, trim(restriction_reason), now(), auth.uid(), true, violation_category, 'community')
  on conflict (user_id) do update set
    banned_until = excluded.banned_until,
    reason = excluded.reason,
    updated_at = now(),
    updated_by = auth.uid(),
    active = true,
    category = excluded.category,
    scope = excluded.scope;

  insert into public.moderation_strikes(user_id, category, points, reason, created_by)
  values (target_user, violation_category, 2, trim(restriction_reason), auth.uid());
  insert into public.moderation_actions(actor_id, action, target_user_id, details)
  values (auth.uid(), 'restrict_user', target_user,
    jsonb_build_object('duration', duration_code, 'until', until_value, 'category', violation_category, 'reason', trim(restriction_reason)));
end;
$$;

