create or replace function public.report_content_v2(
  report_target_type text,
  report_target_id bigint,
  report_category text,
  report_reason text
)
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
  new_id bigint;
  target_exists boolean;
  report_priority text;
begin
  if not public.current_user_can_participate() then raise exception 'ACCOUNT_RESTRICTED'; end if;
  if report_target_type not in ('forum_post', 'forum_reply', 'blog_comment') then raise exception 'INVALID_TARGET'; end if;
  if report_category not in ('harassment', 'privacy', 'spam', 'illegal', 'misinformation', 'other') then raise exception 'INVALID_CATEGORY'; end if;
  if char_length(trim(report_reason)) not between 2 and 300 then raise exception 'INVALID_REASON'; end if;

  if report_target_type = 'forum_post' then
    select exists(select 1 from public.forum_posts where id = report_target_id) into target_exists;
  elsif report_target_type = 'forum_reply' then
    select exists(select 1 from public.forum_replies where id = report_target_id) into target_exists;
  else
    select exists(select 1 from public.comments where id = report_target_id) into target_exists;
  end if;
  if not target_exists then raise exception 'TARGET_NOT_FOUND'; end if;

  report_priority := case when report_category in ('privacy', 'illegal') then 'high' else 'normal' end;
  insert into public.content_reports(reporter_id, target_type, target_id, category, priority, reason)
  values (auth.uid(), report_target_type, report_target_id, report_category, report_priority, trim(report_reason))
  returning id into new_id;
  return new_id;
exception
  when unique_violation then raise exception 'ALREADY_REPORTED';
end;
$$;

