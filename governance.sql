create or replace function public.protect_profile_governance_fields()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if auth.uid() = old.id and not public.current_user_is_admin() then
    if new.is_admin is distinct from old.is_admin
       or new.user_uid is distinct from old.user_uid
       or new.title_locked is distinct from old.title_locked then
      raise exception 'PROTECTED_PROFILE_FIELD';
    end if;
    if old.title_locked and new.display_title is distinct from old.display_title then
      raise exception 'TITLE_LOCKED';
    end if;
  end if;
  return new;
end;
$$;

