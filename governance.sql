create or replace function public.submit_moderation_appeal(appeal_reason text)
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
  new_id bigint;
  latest_action bigint;
begin
  if auth.uid() is null then raise exception 'AUTH_REQUIRED'; end if;
  if char_length(trim(appeal_reason)) not between 10 and 500 then raise exception 'INVALID_APPEAL_REASON'; end if;
  if not exists(select 1 from public.user_moderation m where m.user_id = auth.uid() and m.active = true and (m.banned_until is null or m.banned_until > now())) then
    raise exception 'NO_ACTIVE_RESTRICTION';
  end if;
  select a.id into latest_action from public.moderation_actions a
  where a.target_user_id = auth.uid()
    and (a.action in ('restrict_user', 'ban_user')
      or a.action = 'resolve_report' and coalesce(a.details->>'penalty', 'none') <> 'none')
  order by a.created_at desc limit 1;
  insert into public.moderation_appeals(user_id, action_id, reason)
  values (auth.uid(), latest_action, trim(appeal_reason)) returning id into new_id;
  return new_id;
exception
  when unique_violation then raise exception 'APPEAL_ALREADY_PENDING';
end;
$$;

create or replace function public.admin_review_moderation_appeal(
  target_appeal_id bigint,
  review_decision text,
  moderator_note text
)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  appeal public.moderation_appeals%rowtype;
  newer_action_exists boolean;
begin
  if not public.current_user_is_admin() then raise exception 'ADMIN_REQUIRED'; end if;
  if review_decision not in ('approved', 'rejected') then raise exception 'INVALID_DECISION'; end if;
  if char_length(trim(moderator_note)) not between 2 and 500 then raise exception 'REVIEW_NOTE_REQUIRED'; end if;
  select * into appeal from public.moderation_appeals where id = target_appeal_id for update;
  if not found then raise exception 'APPEAL_NOT_FOUND'; end if;
  if appeal.status <> 'pending' then raise exception 'APPEAL_ALREADY_REVIEWED'; end if;

  select exists(
    select 1 from public.moderation_actions a
    where a.target_user_id = appeal.user_id
      and a.id > coalesce(appeal.action_id, 0)
      and (a.action in ('restrict_user', 'ban_user')
        or a.action = 'resolve_report' and coalesce(a.details->>'penalty', 'none') <> 'none')
  ) into newer_action_exists;
  if review_decision = 'approved' and newer_action_exists then raise exception 'APPEAL_SUPERSEDED'; end if;

  update public.moderation_appeals set status = review_decision, review_note = trim(moderator_note),
    reviewed_at = now(), reviewed_by = auth.uid()
  where id = target_appeal_id;
  if review_decision = 'approved' then
    update public.user_moderation set active = false, banned_until = now(), updated_at = now(), updated_by = auth.uid()
    where user_id = appeal.user_id;
  end if;
  insert into public.moderation_actions(actor_id, action, target_user_id, details)
  values (auth.uid(), 'review_appeal', appeal.user_id,
    jsonb_build_object('appeal_id', target_appeal_id, 'decision', review_decision, 'note', trim(moderator_note)));
end;
$$;

create or replace function public.admin_governance_maintenance()
returns table (expired_restrictions_closed integer, active_restrictions integer, pending_reports integer, pending_appeals integer)
language plpgsql
security definer
set search_path = public
as $$
declare
  closed_count integer;
begin
  if not public.current_user_is_admin() then raise exception 'ADMIN_REQUIRED'; end if;
  update public.user_moderation m set active = false, updated_at = now(), updated_by = auth.uid()
  where m.active = true and m.banned_until is not null and m.banned_until <= now();
  get diagnostics closed_count = row_count;
  insert into public.moderation_actions(actor_id, action, details)
  values (auth.uid(), 'governance_maintenance', jsonb_build_object('expired_restrictions_closed', closed_count));
  return query select closed_count,
    (select count(*)::integer from public.user_moderation m where m.active = true and (m.banned_until is null or m.banned_until > now())),
    (select count(*)::integer from public.content_reports r where r.status = 'pending'),
    (select count(*)::integer from public.moderation_appeals a where a.status = 'pending');
end;
$$;

