import { readFile, writeFile, mkdir } from "node:fs/promises";
import { resolve, join } from "node:path";
import { runInNewContext } from "node:vm";
import { parseHTML } from "linkedom";

const escape = value => String(value ?? "").replace(/[&<>"']/g, char => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" })[char]);
async function readScript(root, file, context) { runInNewContext(await readFile(join(root, file), "utf8"), context, { filename: file, timeout: 1000 }); }

export async function prepareContentIndex(root, { refresh = false } = {}) {
  const sandbox = { window: {} };
  for (const file of ["config.js", "update-log.js", "content-links.js"]) await readScript(root, file, sandbox);
  const logs = sandbox.window.LOCAL_UPDATE_POSTS.filter(post => post.status === "published");
  let index;
  try { index = JSON.parse(await readFile(join(root, "content-pages.json"), "utf8")); }
  catch (error) { if (error.code !== "ENOENT") throw error; index = { version: 1, local: {}, articles: [], threads: [] }; }
  if (index.version !== 1 || !index.local || !Array.isArray(index.articles) || !Array.isArray(index.threads)) throw new Error("Invalid content-pages.json");
  const existing = Object.values(index.local).map(record => record.commentId);
  let nextCommentId = existing.length ? Math.max(...existing) + 1 : 9000000;
  const initialized = existing.length > 0;
  const seen = new Set();
  logs.forEach((post, position) => {
    const key = sandbox.window.blogContentLinks.localKey(post);
    if (!/^[a-z0-9-]+$/.test(key) || seen.has(key)) throw new Error(`Duplicate/invalid article permalink: ${key}`);
    seen.add(key);
    if (!index.local[key]) index.local[key] = { commentId: initialized ? nextCommentId++ : 9000000 + position };
  });
  if (refresh) {
    const { supabaseUrl, supabasePublishableKey } = sandbox.window.BLOG_CONFIG;
    if (!/^sb_publishable_/.test(supabasePublishableKey || "")) throw new Error("Use the public publishable key, never an admin/service role key.");
    const readIds = async table => {
      const ids = [];
      for (let offset = 0; ; offset += 500) {
        const url = new URL(`/rest/v1/${table}`, supabaseUrl);
        url.search = new URLSearchParams({ select: "id", order: "id.asc", limit: "500", offset: String(offset), ...(table === "posts" ? { status: "eq.published" } : {}) });
        const response = await fetch(url, { headers: { apikey: supabasePublishableKey }, signal: AbortSignal.timeout(20000) });
        if (!response.ok) throw new Error(`Public ${table} index request failed (HTTP ${response.status}). Existing index retained.`);
        const rows = await response.json();
        if (!Array.isArray(rows) || rows.some(row => !sandbox.window.blogContentLinks.positiveId(row.id))) throw new Error(`Invalid IDs returned by ${table}`);
        ids.push(...rows.map(row => Number(row.id)));
        if (rows.length < 500) return [...new Set(ids)];
      }
    };
    // Persist neither titles, authors nor bodies from the database. These pages
    // re-check the current public row at read time, including after moderation.
    const [articles, threads] = await Promise.all([readIds("posts"), readIds("forum_posts")]);
    const changed = JSON.stringify(index.articles) !== JSON.stringify(articles)
      || JSON.stringify(index.threads) !== JSON.stringify(threads);
    index.articles = articles;
    index.threads = threads;
    // Keep no-op builds byte-for-byte stable. This lets automation distinguish
    // a real public-content change from a routine scheduled check.
    if (changed || !index.refreshedAt) index.refreshedAt = new Date().toISOString();
  }
  await writeFile(join(root, "content-pages.json"), JSON.stringify(index, null, 2) + "\n");
  await writeFile(join(root, "content-index.js"), `// Generated by tools/build-content-pages.mjs; do not edit.\nwindow.BLOG_CONTENT_INDEX = ${JSON.stringify(index)};\n`);
  return { index, logs, config: sandbox.window.BLOG_CONFIG, links: sandbox.window.blogContentLinks };
}

