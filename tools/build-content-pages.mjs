export async function buildContentPages(root, html, prepared) {
  const { index, logs, config, links } = prepared;
  const sandbox = { window: {}, document: parseHTML("<!doctype html><html><body></body></html>").document };
  await readScript(root, "markdown.js", sandbox);
  const canonicalRoot = new URL(config.siteUrl);
  if (!/^https?:$/.test(canonicalRoot.protocol)) throw new Error("Invalid public site URL");
  const generated = [];
  const displayDate = value => {
    const normalized = /^\d{4}-\d{2}-\d{2}$/.test(String(value)) ? `${value}T00:00:00+08:00` : value;
    const date = new Date(normalized);
    if (Number.isNaN(date.getTime())) return String(value || "");
    const parts = Object.fromEntries(new Intl.DateTimeFormat("zh-CN", { timeZone: "Asia/Shanghai", year: "numeric", month: "2-digit", day: "2-digit", hour: "2-digit", minute: "2-digit", second: "2-digit", hourCycle: "h23" }).formatToParts(date).filter(part => part.type !== "literal").map(part => [part.type, part.value]));
    return `${parts.year}-${parts.month}-${parts.day} ${parts.hour}:${parts.minute}:${parts.second}`;
  };
  async function page(kind, key, localPost = null) {
    const filename = key ? `${kind === "thread" ? "threads" : "articles"}/${key}.html` : `${kind === "thread" ? "thread" : "article"}.html`;
    const prefix = key ? "../" : "./";
    const title = localPost?.title || (kind === "thread" ? "社区帖子" : "博客文章");
    const description = localPost?.description || "在 cnbdg 的社区阅读内容，参与友善讨论。";
    const { document } = parseHTML(html);
    document.title = `${title} · cnbdg的博客`;
    document.querySelector('meta[name="description"]').content = description;
    document.querySelector('meta[property="og:title"]').content = title;
    document.querySelector('meta[property="og:description"]').content = description;
    document.querySelector('meta[property="og:type"]').content = "article";
    const canonical = new URL(filename, canonicalRoot).href;
    document.head.insertAdjacentHTML("beforeend", `<link rel="canonical" href="${escape(canonical)}"><meta property="og:url" content="${escape(canonical)}"><meta name="twitter:card" content="summary">`);
    document.querySelectorAll('script[src],link[rel="stylesheet"][href]').forEach(node => {
      const attr = node.tagName === "SCRIPT" ? "src" : "href";
      const value = node.getAttribute(attr);
      if (!/^(?:https?:|\/\/)/.test(value)) node.setAttribute(attr, prefix + value);
    });
    document.body.classList.add("reader-page");
    document.body.dataset.readerKind = kind;
    if (key) document.body.dataset.readerKey = key;
    document.querySelector("#app").setAttribute("aria-hidden", "true");
    document.body.insertAdjacentHTML("afterbegin", renderReaderShell(kind, prefix));
    const source = document.getElementById(kind === "thread" ? "threadDialog" : "articleDialog");
    const section = document.createElement("section");
    section.id = source.id;
    section.className = "reader-document";
    section.setAttribute("data-reader-inline", "");
    section.innerHTML = source.innerHTML;
    section.querySelector(".article-close")?.remove();
    source.remove();
    document.getElementById("readerMount").append(section);
    section.querySelector(".comments").id = "readerDiscussion";
    section.querySelector(".comments").setAttribute("tabindex", "-1");
    if (localPost) {
      const dateText = displayDate(localPost.published_at);
      section.querySelector("#articleContent").innerHTML = `<div class="article-body"><div class="article-meta">${escape(localPost.type)} · <time datetime="${escape(localPost.published_at)}">${escape(dateText)}</time> · ${escape(localPost.read_time)}</div><h1>${escape(title)}</h1><p class="lead">${escape(localPost.lead)}</p><div class="article-text">${sandbox.window.blogMarkdown.render(localPost.body)}</div></div>`;
      document.getElementById("readerState").hidden = true;
    } else section.hidden = true;
    document.body.insertAdjacentHTML("beforeend", `<noscript><p class="reader-noscript">${localPost ? "正文可以直接阅读；评论和分享工具需要启用 JavaScript。" : "请启用 JavaScript 以读取最新公开内容和讨论。"}</p></noscript>`);
    const target = resolve(root, filename);
    if (!target.startsWith(resolve(root) + "/") && !target.startsWith(resolve(root) + "\\")) throw new Error("Unsafe output path");
    await mkdir(resolve(target, ".."), { recursive: true });
    await writeFile(target, "<!-- Generated reader page; edit source content, not this file. -->\n" + document.toString());
    generated.push(filename);
  }
  await page("article", null);
  await page("thread", null);
  for (const post of logs) await page("article", links.localKey(post), post);
  for (const id of index.articles) await page("article", `post-${id}`);
  for (const id of index.threads) await page("thread", String(id));
  console.log(`Reader pages: ${logs.length} local articles, ${index.articles.length} published database articles, ${index.threads.length} threads, 2 fallback entries.`);
  return generated;
}
